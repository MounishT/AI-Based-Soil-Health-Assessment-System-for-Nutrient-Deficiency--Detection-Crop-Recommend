from fastapi import APIRouter, HTTPException
from fastapi.responses import FileResponse
from pydantic import BaseModel
from typing import Optional, List, Dict, Any
import os
import uuid
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib import colors

router = APIRouter(prefix="/api/v1/report", tags=["Report Generation"])

class ReportRequest(BaseModel):
    soil_health_score: float
    health_band: str
    diagnosis: Dict[str, str]
    crop_ranking: List[Dict[str, Any]]
    fertilizer_recommendation: List[Dict[str, str]]
    input_values: Optional[Dict[str, Any]] = None

@router.post("/generate")
def generate_pdf_report(request: ReportRequest):
    """
    Generates a PDF report summarizing soil health analysis and recommendations.
    """
    # Ensure temporary directory exists
    reports_dir = os.path.join(os.getcwd(), "reports")
    os.makedirs(reports_dir, exist_ok=True)
    
    file_id = str(uuid.uuid4())
    pdf_path = os.path.join(reports_dir, f"soil_report_{file_id}.pdf")
    
    c = canvas.Canvas(pdf_path, pagesize=letter)
    width, height = letter
    
    # Title
    c.setFont("Helvetica-Bold", 20)
    c.drawString(50, height - 50, "Soil Health Assessment Report")
    
    # Health Score
    c.setFont("Helvetica-Bold", 14)
    c.setFillColor(colors.darkgreen if request.health_band == "good" else colors.darkred)
    c.drawString(50, height - 90, f"Soil Health Score: {request.soil_health_score}/100 ({request.health_band.upper()})")
    
    # Soil Inputs
    c.setFillColor(colors.black)
    c.setFont("Helvetica-Bold", 14)
    c.drawString(50, height - 130, "Soil Inputs:")
    c.setFont("Helvetica", 12)
    
    y = height - 150
    if request.input_values:
        for k, v in request.input_values.items():
            c.drawString(70, y, f"- {k.capitalize()}: {v}")
            y -= 20
    else:
        c.drawString(70, y, "- No inputs provided")
        y -= 20
        
    y -= 10
    
    # Diagnosis
    c.setFont("Helvetica-Bold", 14)
    c.drawString(50, y, "Nutrient Diagnosis:")
    c.setFont("Helvetica", 12)
    
    y -= 20
    for nutrient, status in request.diagnosis.items():
        c.drawString(70, y, f"- {nutrient.capitalize()}: {status.capitalize()}")
        y -= 20
        
    # Crop Recommendations
    y -= 20
    c.setFont("Helvetica-Bold", 14)
    c.drawString(50, y, "Top Crop Recommendations:")
    c.setFont("Helvetica", 12)
    y -= 20
    for crop in request.crop_ranking:
        c.drawString(70, y, f"- {crop['crop']} (Suitability: {crop['suitability_score']}/100)")
        y -= 20

    # Fertilizer Dosages
    y -= 20
    c.setFont("Helvetica-Bold", 14)
    c.drawString(50, y, "Fertilizer Recommendations:")
    c.setFont("Helvetica", 10)
    y -= 20
    for fert in request.fertilizer_recommendation:
        c.drawString(70, y, f"{fert['nutrient']}: {fert['fertilizer_type']} | Dose: {fert['dosage_kg_per_acre']} kg/acre")
        y -= 15
        c.drawString(90, y, f"Schedule: {fert['schedule']}")
        y -= 20
        
    # Footer
    c.setFont("Helvetica-Oblique", 10)
    c.drawString(50, 50, "Generated by AI-Based Soil Health Assessment System")
    
    c.save()
    
    return FileResponse(pdf_path, media_type="application/pdf", filename="Soil_Health_Report.pdf")
